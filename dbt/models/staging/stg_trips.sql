-- Typed, renamed view over the raw landing table. No filtering: every source row is visible here.
select
    record_id,
    partition_id,
    source_row,
    vendor_id,
    pickup_datetime,
    dropoff_datetime,
    extract(epoch from (dropoff_datetime - pickup_datetime)) / 60.0 as trip_duration_min,
    pickup_datetime::date                                           as pickup_date,
    passenger_count,
    trip_distance,
    ratecode_id,
    store_and_fwd_flag,
    pu_location_id,
    do_location_id,
    payment_type,
    fare_amount,
    extra,
    mta_tax,
    tip_amount,
    tolls_amount,
    improvement_surcharge,
    total_amount,
    congestion_surcharge,
    airport_fee,
    cbd_congestion_fee,
    loaded_run_id
from {{ source('raw', 'yellow_trips') }}
